// 두께도 앞면과 같은 배율로 (2026-11-08 사용자: "핀볼의 첫번째 사진의 측면간판 두께가 과도하게 나온다. 이러한 상태는 자주 발생하는데 조정이 어렵다").
// 3D 는 앞면(가로·세로)을 그린 외곽선(그 면의 mm)에 맞춰 늘이고 줄이는데 두께는 입력 mm 그대로였다 — 핀볼 정사선 사진의 측면간판은
// 입력 3200×600 이 면에서 1663×310 으로 재져 앞면만 0.52 배, 두께 120 은 그대로라 두께가 크기에 비해 두 배로 보였다
import { describe, expect, it } from 'vitest';
import { depthScale } from '../../src/lib/core/render';

describe('depthScale — 앞면을 맞춘 배율만큼 두께도', () => {
  it('외곽선이 입력 크기와 같으면 1', () => {
    expect(depthScale([[-1000, 500], [1000, 500], [1000, -500], [-1000, -500]], 2000, 1000)).toBeCloseTo(1, 6);
  });
  it('핀볼 측면간판: 3200×600 이 1663×310 으로 재지면 약 0.52', () => {
    expect(depthScale([[0, 310], [1663, 310], [1663, 0], [0, 0]], 3200, 600)).toBeCloseTo(Math.sqrt((1663 / 3200) * (310 / 600)), 6);
  });
  it('가로·세로 배율이 다르면 둘의 기하 평균, 사다리꼴은 마주 보는 변의 평균', () => {
    expect(depthScale([[0, 100], [400, 100], [400, 0], [0, 0]], 200, 100)).toBeCloseTo(Math.SQRT2, 6);
    expect(depthScale([[0, 100], [300, 100], [250, 0], [50, 0]], 250, 100)).toBeCloseTo(Math.sqrt((250 / 250) * (Math.hypot(50, 100) / 100)), 6); // 위 300·아래 200 → 250, 옆 변 √(50²+100²)
  });
  it('찌그러져 크기를 잴 수 없으면 1', () => {
    expect(depthScale([[0, 0], [0, 0], [0, 0], [0, 0]], 200, 100)).toBe(1);
    expect(depthScale([[0, 100], [200, 100], [200, 0], [0, 0]], 0, 100)).toBe(1);
  });
});
