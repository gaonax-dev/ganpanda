import { describe, expect, it } from 'vitest';
import { arrangeLikePhotos } from '../../src/lib/core/arrange';
import { placeholderSize } from '../../src/lib/core/boardCards';

// 2026-10-23 사용자: "사진보드 정면도 사인물 카드 정렬이 마지막 사진에서 겹쳐지고 잘 정렬되지 않았다" → "재정렬하면"
// 실제 프로젝트 마지막 사진(3200×2400)의 치수 없는 사인물 20개 외곽선 — 임시 카드 가로 1000mm 가 사진 속 자리보다 커서 많이 겹친다
const QUADS: [number, number][][] = [[[815, 949], [1229, 972], [1226, 1797], [811, 1851]], [[822, 530], [1619, 646], [1608, 938], [820, 876]], [[671, 907], [773, 913], [769, 1846], [667, 1859]], [[665, 493], [782, 510], [780, 864], [663, 855]], [[1652, 634], [1729, 646], [1731, 931], [1654, 925]], [[1743, 974], [1969, 989], [1969, 1406], [1743, 1418]], [[1744, 657], [1982, 688], [1977, 954], [1745, 938]], [[1269, 964], [1598, 983], [1597, 1785], [1266, 1831]], [[2007, 691], [2174, 716], [2174, 970], [2007, 957]], [[2007, 996], [2166, 1006], [2166, 1173], [2007, 1170]], [[2021, 1217], [2155, 1217], [2155, 1392], [2021, 1399]], [[2200, 1001], [2481, 1019], [2481, 1383], [2200, 1397]], [[2195, 717], [2493, 761], [2493, 992], [2195, 970]], [[2507, 767], [2632, 784], [2632, 1003], [2507, 995]], [[2514, 1022], [2632, 1029], [2632, 1185], [2514, 1184]], [[2519, 1215], [2636, 1216], [2636, 1366], [2519, 1371]], [[2643, 790], [2785, 805], [2786, 1017], [2644, 1002]], [[2657, 1035], [2778, 1043], [2778, 1371], [2656, 1377]], [[1495, 287], [2453, 504], [2453, 678], [1494, 514]], [[241, 1206], [444, 1207], [442, 1463], [239, 1473]]];

describe('재정렬: 카드가 서로 겹치지 않는다', () => {
  it.each([6000, 3000, 12000])('사진 폭 %imm — 이름 줄·간격 포함 겹침 없음', (photoMm) => {
    const photo = { x: 0, y: 0, w: photoMm, h: photoMm * 0.75, imgW: 3200, imgH: 2400 };
    const cards = QUADS.map((q, i) => {
      const s = placeholderSize(q);
      const xs = q.map((p) => p[0]), ys = q.map((p) => p[1]);
      return { id: 'c' + i, w: s.w, h: s.h, photo: 0, box: { x0: Math.min(...xs), y0: Math.min(...ys), x1: Math.max(...xs), y1: Math.max(...ys) } };
    });
    const gap = 600, label = 100;
    const at = arrangeLikePhotos(cards, [photo], gap, label);
    const R = cards.map((c) => ({ id: c.id, x: at.get(c.id)!.x, y: at.get(c.id)!.y, w: c.w, h: c.h + label }));
    const bad: string[] = [];
    for (let i = 0; i < R.length; i++) for (let j = i + 1; j < R.length; j++) {
      const a = R[i], b = R[j];
      if (a.x < b.x + b.w && b.x < a.x + a.w && a.y < b.y + b.h && b.y < a.y + a.h) bad.push(a.id + '×' + b.id);
    }
    expect(bad).toEqual([]);
  });
});
